// Builds the SCENE logo as pure SVG paths (no font needed at render time).
// Usage: node tools/build-logo.mjs   (needs opentype.js; set OPENTYPE to its path)
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const require = createRequire(import.meta.url);
const opentype = require(process.env.OPENTYPE || 'opentype.js');
const font = opentype.loadSync(path.join(here, 'urbanist-900.ttf'));
const upm = font.unitsPerEm;
const capH = font.tables.os2.sCapHeight || 700;

// ---------- Icon (512 x 512) ----------
const SIZE = 512, R = Math.round(SIZE * 0.26);
const targetCap = SIZE * 0.70;
const fs1 = targetCap / capH * upm;
let sPath = font.getPath('S', 0, 0, fs1);
let bb = sPath.getBoundingBox();
const dx = (SIZE - (bb.x2 - bb.x1)) / 2 - bb.x1 - SIZE * 0.012;   // tiny left bias leaves room for the dot
const dy = (SIZE - (bb.y2 - bb.y1)) / 2 - bb.y1 + SIZE * 0.012;   // optical centre sits a touch low
sPath = font.getPath('S', dx, dy, fs1);
bb = sPath.getBoundingBox();
const sD = sPath.toPathData(2);
// point of light: just off the S's upper-right terminal
const dotX = (bb.x2 + SIZE * 0.035).toFixed(1), dotY = (bb.y1 + SIZE * 0.045).toFixed(1);

function icon(p = 'lg') {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${SIZE} ${SIZE}" width="100%" height="100%" aria-label="SCENE">
  <defs>
    <linearGradient id="${p}-bg" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#6FE8FA"/><stop offset="0.36" stop-color="#36A9FF"/><stop offset="0.72" stop-color="#2F6BFF"/><stop offset="1" stop-color="#2A4FD6"/>
    </linearGradient>
    <linearGradient id="${p}-gloss" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#fff" stop-opacity="0.55"/><stop offset="1" stop-color="#fff" stop-opacity="0"/>
    </linearGradient>
    <linearGradient id="${p}-s" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#FFFFFF"/><stop offset="1" stop-color="#EAF6FF"/>
    </linearGradient>
    <radialGradient id="${p}-dot">
      <stop offset="0" stop-color="#fff"/><stop offset="0.35" stop-color="#fff" stop-opacity="0.9"/><stop offset="1" stop-color="#E6FBFF" stop-opacity="0"/>
    </radialGradient>
    <filter id="${p}-sh" x="-20%" y="-20%" width="140%" height="140%"><feDropShadow dx="0" dy="${SIZE*0.012}" stdDeviation="${SIZE*0.016}" flood-color="#14307a" flood-opacity="0.35"/></filter>
    <clipPath id="${p}-clip"><rect width="${SIZE}" height="${SIZE}" rx="${R}"/></clipPath>
  </defs>
  <g clip-path="url(#${p}-clip)">
    <rect width="${SIZE}" height="${SIZE}" fill="url(#${p}-bg)"/>
    <path d="M0 0H${SIZE}V${SIZE*0.30}C${SIZE*0.70} ${SIZE*0.43} ${SIZE*0.30} ${SIZE*0.43} 0 ${SIZE*0.36}Z" fill="url(#${p}-gloss)"/>
    <rect x="1.5" y="1.5" width="${SIZE-3}" height="${SIZE-3}" rx="${R-1.5}" fill="none" stroke="#fff" stroke-opacity="0.35" stroke-width="3"/>
  </g>
  <path d="${sD}" fill="url(#${p}-s)" filter="url(#${p}-sh)"/>
  <circle cx="${dotX}" cy="${dotY}" r="${SIZE*0.085}" fill="url(#${p}-dot)" opacity="0.85"/>
  <circle cx="${dotX}" cy="${dotY}" r="${SIZE*0.026}" fill="#fff"/>
</svg>`;
}

// ---------- Wordmark "SCENE", letter-spacing 0.14em ----------
const WF = 200; // font size in user units
const track = 0.14 * WF;
let x = 0; const parts = [];
for (const ch of 'SCENE') {
  const g = font.charToGlyph(ch);
  parts.push(font.getPath(ch, x, 0, WF).toPathData(2));
  x += g.advanceWidth / upm * WF + track;
}
x -= track; // no trailing tracking
const wp = font.getPath('SCENE', 0, 0, WF); // for vertical metrics
const wcap = capH / upm * WF;
const ww = Math.ceil(x), wh = Math.ceil(wcap);
function wordmark(p = 'wm') {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 ${(-wcap).toFixed(1)} ${ww} ${wh}" width="100%" height="100%" aria-label="SCENE">
  <defs><linearGradient id="${p}-g" x1="0" y1="0" x2="${ww}" y2="0" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="#0B1A2E"/><stop offset="0.55" stop-color="#1D3F8F"/><stop offset="1" stop-color="#2F6BFF"/></linearGradient></defs>
  <path d="${parts.join(' ')}" fill="url(#${p}-g)"/>
</svg>`;
}

fs.writeFileSync(path.join(root, 'assets/brand/icon.svg'), icon('ic'));
fs.writeFileSync(path.join(root, 'assets/brand/wordmark.svg'), wordmark('wm'));
fs.writeFileSync(path.join(root, 'src/logo-data.json'), JSON.stringify({ size: SIZE, radius: R, sD, dot: [+dotX, +dotY], sBox: bb, word: { d: parts, width: ww, cap: wcap } }, null, 0));
// ESM helper for scenes (inline SVG with unique gradient ids)
fs.writeFileSync(path.join(root, 'src/logo.mjs'),
`// Generated by tools/build-logo.mjs — do not edit by hand.
const data = ${JSON.stringify({ SIZE, R, sD, dotX: +dotX, dotY: +dotY, ww, wcap, parts })};
export const LOGO = data;
export ${icon.toString().replace(/\$\{SIZE\}/g, '${data.SIZE}').replace(/\$\{SIZE\*([0-9.]+)\}/g, (m, k) => '${data.SIZE*' + k + '}').replace(/\$\{SIZE-3\}/g, '${data.SIZE-3}').replace(/\$\{R\}/g, '${data.R}').replace(/\$\{R-1\.5\}/g, '${data.R-1.5}').replace(/\$\{sD\}/g, '${data.sD}').replace(/\$\{dotX\}/g, '${data.dotX}').replace(/\$\{dotY\}/g, '${data.dotY}')}
export ${wordmark.toString().replace(/\$\{ww\}/g, '${data.ww}').replace(/\$\{wh\}/g, '${Math.ceil(data.wcap)}').replace(/\$\{\(-wcap\)\.toFixed\(1\)\}/g, '${(-data.wcap).toFixed(1)}').replace(/\$\{parts\.join\(' '\)\}/g, "${data.parts.join(' ')}")}
`);
console.log('icon S cap', targetCap.toFixed(0), 'bbox', JSON.stringify(bb), 'dot', dotX, dotY, 'wordmark', ww, 'x', wh);
