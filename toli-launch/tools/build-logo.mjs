// toli logo: three overlapping circles (the crew coming together) + "toli" wordmark from Bricolage Grotesque 800 paths.
// Writes assets/brand/icon.svg, wordmark.svg, lockup.svg and src/logo.mjs (inline SVG builders with animatable ids).
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url)), root = path.resolve(here, '..');
const require = createRequire(import.meta.url);
const opentype = require(process.env.OPENTYPE || 'opentype.js');
const font = opentype.loadSync(path.join(here, 'bricolage-800.ttf'));
const upm = font.unitsPerEm;

// ---- wordmark: t o l ı + a marigold dot
const FS = 200, track = -0.01 * FS;
let x = 0; const d = [];
for (const ch of ['t', 'o', 'l', 'ı']) { const g = font.charToGlyph(ch); d.push(font.getPath(ch, x, 0, FS).toPathData(2)); x += g.advanceWidth / upm * FS + track; }
const all = font.getPath('toli', 0, 0, FS).getBoundingBox();
const iBox = font.getPath('ı', x - (font.charToGlyph('ı').advanceWidth / upm * FS + track), 0, FS).getBoundingBox();
const xh = (font.tables.os2.sxHeight || 500) / upm * FS;
const asc = -all.y1; // tallest (t, l) above baseline
const dotR = (iBox.x2 - iBox.x1) * 0.62, dotCx = (iBox.x1 + iBox.x2) / 2, dotCy = -xh - dotR * 1.55;
const top = Math.min(-asc, dotCy - dotR) - 4, W = Math.ceil(x - track + 6), H = Math.ceil(-top + 4);
const WM = { d, W, H, top: +top.toFixed(1), dot: [+dotCx.toFixed(1), +dotCy.toFixed(1), +dotR.toFixed(1)] };

// ---- icon: squircle, three circles in screen blend
const S = 512, R = Math.round(S * 0.28), cr = 118, off = 66;
const C = [[S / 2 - off * 0.87, S / 2 - off * 0.5 + 6, '#FF3D81'], [S / 2 + off * 0.87, S / 2 - off * 0.5 + 6, '#FFB627'], [S / 2, S / 2 + off + 6, '#20C9B5']];
const IC = { S, R, cr, C };

const logoSrc = `// Generated by tools/build-logo.mjs — toli brand mark.
export const WM = ${JSON.stringify(WM)};
export const IC = ${JSON.stringify(IC)};
/** App icon. Circles carry ids \`\${p}-c0..2\` so scenes can fly them in. */
export function icon(p = 'ic', { bg = true } = {}) {
  const { S, R, cr, C } = IC;
  return \`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 \${S} \${S}" width="100%" height="100%" aria-label="toli">
  <defs>
    <linearGradient id="\${p}-bg" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#2C1C48"/><stop offset="1" stop-color="#150C26"/></linearGradient>
    <clipPath id="\${p}-clip"><rect width="\${S}" height="\${S}" rx="\${R}"/></clipPath>
  </defs>
  \${bg ? \`<g clip-path="url(#\${p}-clip)"><rect width="\${S}" height="\${S}" fill="url(#\${p}-bg)"/><rect x="2" y="2" width="\${S - 4}" height="\${S - 4}" rx="\${R - 2}" fill="none" stroke="#FFF3E2" stroke-opacity="0.12" stroke-width="4"/></g>\` : ''}
  <g style="isolation:isolate">\${C.map(([x, y, c], k) => \`<circle id="\${p}-c\${k}" cx="\${x}" cy="\${y}" r="\${cr}" fill="\${c}" style="mix-blend-mode:screen"/>\`).join('')}</g>
</svg>\`;
}
/** Wordmark "toli" (cream) with a marigold dot (id \`\${p}-dot\`). */
export function wordmark(p = 'wm', { color = '#FFF3E2', dot = '#FFB627' } = {}) {
  const { d, W, H, top, dot: [cx, cy, r] } = WM;
  return \`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 \${top} \${W} \${H}" width="100%" height="100%" aria-label="toli">
  <path d="\${d.join(' ')}" fill="\${color}"/><circle id="\${p}-dot" cx="\${cx}" cy="\${cy}" r="\${r}" fill="\${dot}"/>
</svg>\`;
}
`;
fs.writeFileSync(path.join(root, 'src/logo.mjs'), logoSrc);
const { icon, wordmark } = await import(path.join(root, 'src/logo.mjs') + '?v=' + Date.now());
fs.writeFileSync(path.join(root, 'assets/brand/icon.svg'), icon('ic'));
fs.writeFileSync(path.join(root, 'assets/brand/wordmark.svg'), wordmark('wm'));
console.log('wordmark', W, 'x', H, 'dot', WM.dot, '| icon circles r', cr);
